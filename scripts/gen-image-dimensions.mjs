import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const imagesDir = path.join(root, 'src', 'assets', 'images')
const outFile = path.join(root, 'src', 'data', 'imageDimensions.ts')

const files = fs
  .readdirSync(imagesDir)
  .filter((name) => /\.(webp|png|jpe?g)$/i.test(name))
  .sort()

const entries = []
for (const name of files) {
  const meta = await sharp(path.join(imagesDir, name)).metadata()
  if (!meta.width || !meta.height) continue
  entries.push(`  '${name}': { width: ${meta.width}, height: ${meta.height} },`)
}

const source = `/* Auto-generated by scripts/gen-image-dimensions.mjs — do not edit by hand. */
export type ImageDimension = { width: number; height: number }

export const imageDimensions: Record<string, ImageDimension> = {
${entries.join('\n')}
}
`

fs.writeFileSync(outFile, source, 'utf8')
console.log(`Wrote ${entries.length} image dimensions to ${path.relative(root, outFile)}`)
